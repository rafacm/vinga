def _view_section(view: View) -> list[str]:
    lines = [
        f"### `{view.name}`",
        "",
        *_paragraph(view.question),
        "",
        "| Column | Type | Null | Units | Meaning | Formula |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    lines += [
        f"| `{column.name}` | `{column.type}` | {_null(column.nullable)} | "
        f"{_cell(column.units)} | {_cell(column.meaning)} | {_cell(column.formula)} |"
        for column in view.columns
    ]
    lines += [
        "",
        *_paragraph("**Denominator.** " + view.denominator),
        "",
        *_paragraph("**Telemetry-off.** " + view.telemetry_off),
        "",
    ]
    return lines


def _table_section(table: Table) -> list[str]:
    lines = [
        f"### `{table.name}`",
        "",
        "| Column | Type | Null | Description |",
        "| --- | --- | --- | --- |",
    ]
    lines += [
        f"| `{column.name}` | `{column.type}` | {_null(column.nullable)} | "
        f"{_cell(column.comment)} |"
        for column in table.columns
    ]
    lines.append("")
    return lines


def _null(nullable: bool) -> str:
    return "yes" if nullable else "no"


def _cell(comment: str | None) -> str:
    """Text inside a table cell. A pipe ends a cell even inside a code
    span, so it is escaped; and an undescribed column is a defect this
    makes visible rather than an empty cell to skim past."""
    if not comment:
        return "**(undescribed)**"
    return " ".join(comment.split()).replace("|", "\\|")


def _paragraph(prose: str) -> list[str]:
    """One paragraph, wrapped. The committed reference is read as a file
    as often as it is rendered, and an unwrapped paragraph makes every
    edit to it a one-line diff of the whole thing.

    Never inside a word or across a hyphen, for the reason the domain
    reference gives: the default would break an identifier in half and a
    code span split over two lines renders with a space in it."""
    return textwrap.wrap(prose, width=PROSE_WIDTH, break_long_words=False, break_on_hyphens=False)


